def cp_upper_vec(x, n, alpha=ALPHA):
    x = np.asarray(x, float)
    out = np.ones_like(x)
    ok = x < n
    out[ok] = stats.beta.ppf(1 - alpha, x[ok] + 1, n - x[ok])
    return out


def first_true(mask):
    i = int(np.argmax(mask))
    assert mask[i], "threshold beyond XMAX"
    return i


# Bounds that are fixed functions of X (or of Y, the scenarios with an event).
UB_NAIVE = cp_upper_vec(XS, N)
UB_KISH = {f: {r: cp_upper_vec(XS / deff(M, min(f * r, 1.0)), N / deff(M, min(f * r, 1.0)))
               for r in RHOS} for f in (0.5, 1.0, 2.0)}
UB_ANY = np.array([any_event_upper(y, K) for y in range(K + 1)])
FTAG = {0.5: "half", 1.0: "true", 2.0: "double"}


def coverage_cell(mu, rho, truths=tuple(TRUTHS)):
    """Exact coverage of every method at true mean mu and ICC rho, one row per truth.
    Each method covers iff X >= its threshold x0 (Y >= y0 for the scenario bound),
    because every bound is non-decreasing in the count."""
    x0 = {"naive": first_true(UB_NAIVE >= mu)}
    for f, tag in FTAG.items():
        r = min(f * rho, 1.0)
        x0[f"kish_{tag}"] = first_true(UB_KISH[f][rho] >= mu)
        # exact (Beta) and worst-case bounds: covered iff P_assumed(X <= x | mu) >= alpha
        x0[f"exact_{tag}"] = first_true(np.cumsum(sum_pmf_iid(cluster_pmf(M, mu, r), K, XMAX)) >= ALPHA)
        x0[f"wctp_{tag}"] = first_true(np.cumsum(sum_pmf_iid(cluster_pmf_twopoint(M, mu, r), K, XMAX)) >= ALPHA)
        # worst-case bound = max(two-point, Beta) bound, so it covers iff either does
        x0[f"wc_{tag}"] = min(x0[f"wctp_{tag}"], x0[f"exact_{tag}"])
    y0 = first_true(UB_ANY >= mu)
    rows = []
    for t in truths:
        cp = TRUTHS[t](M, mu, rho)
        cdf = np.cumsum(sum_pmf_iid(cp, K, XMAX))
        row = dict(mu=mu, rho=rho, truth=t, p_zero=float(cp[0] ** K))
        for meth, x in x0.items():
            row[meth] = 1.0 if x == 0 else float(1.0 - cdf[x - 1])
        row["scenario"] = float(stats.binom.sf(y0 - 1, K, 1.0 - cp[0]))
        rows.append(row)
    return rows


