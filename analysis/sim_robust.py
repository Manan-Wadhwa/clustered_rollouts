"""How much do the zero-event bounds depend on the Beta shape?

Compares six bounds: naive (Clopper-Pearson on N), exact beta-binomial at the true
ICC and at half of it, Kish, the worst-case bound over all rate distributions with
the given mean and ICC (bounds_extra.wc_upper: exact worst case at zero events, the
larger of the two-point and Beta bounds otherwise), and the scenario (any-event)
bound. The CSVs also carry `wctp_*`, the two-point bound alone.
Truths: Beta, the two-point law with an atom at 0 (the worst case for zero events),
logit-normal, and a zero-inflated Beta halfway between the two. All four share the
mean and ICC. Coverage is exact: every bound here depends on the data only through
the total count X (or the number of scenarios with an event), so coverage is a sum
over the distribution of X.

Also: zero-event bounds with the worst case added (Table 5 setting included), the
optimal rollouts per scenario under each bound for a budget with a scenario-writing
cost, the wordings comparison at equal prompt counts, and macros for the Monte Carlo
checks written by sim.py and sim_extra.py.

Reads data/sim_coverage.csv (sim.py), data/sim_mc_check.csv, data/sim_extra_coverage.csv,
data/sim_extra_budget.csv, data/sim_extra_nested.csv (sim_extra.py) and
data/rollouts_opus.csv. Writes paper/numbers_robust.tex, paper/tab_robust_*.tex,
paper/figs/coverage.pdf and data/sim_robust_*.csv.
Run after sim.py and sim_extra.py: uv run analysis/sim_robust.py
"""
