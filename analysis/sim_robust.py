# ---- 4. Budget: optimal m under the exact, Kish and worst-case bounds (B13) -----------
print("\n== 4. budget optima under three bounds ==")
RATIOS, BRHOS = (0, 10, 100), (0.05, 0.2)
CRIT = ("exact", "kish", "wc")


def ub_design(K_, m_, r):
    return dict(exact=bb_zero_upper(K_, m_, r), kish=adjusted_upper(0, K_ * m_, deff(m_, r)),
                wc=wc_zero_upper(K_, m_, r))


ex_budget = read_csv("sim_extra_budget.csv")
budget_rows = []
for cs in RATIOS:
    B = K * (cs + M)
    mmax = B - cs
    for r in BRHOS:
        cache = {}

        def evaluate(ms):
            for m_ in ms:
                K_ = int(B // (cs + m_))
                if K_ >= 1 and m_ not in cache:
                    cache[m_] = (K_, ub_design(K_, int(m_), r))

        evaluate(np.unique(np.round(np.logspace(0, np.log10(mmax), 250)).astype(int)))
        near = set()
        for crit in CRIT:  # refine around each coarse optimum on every integer m
            c0 = min(cache, key=lambda m_: cache[m_][1][crit])
            near |= set(range(max(1, int(c0 / 1.6)), min(mmax, int(c0 * 1.6) + 2) + 1))
        evaluate(sorted(near))
        row = dict(c_ratio=cs, rho=r, budget=B, classical_m=float(np.sqrt(cs * (1 - r) / r)))
        for crit in CRIT:
            mo = min(cache, key=lambda m_: cache[m_][1][crit])
            row[f"opt_m_{crit}"] = int(mo)
            row[f"opt_K_{crit}"] = cache[mo][0]
            row[f"opt_ub_{crit}"] = cache[mo][1][crit]
        # what the worst-case bound is at the design the exact bound picks
        row["wc_at_exact_opt"] = cache[row["opt_m_exact"]][1]["wc"]
        budget_rows.append(row)
        print({k_: (round(v, 5) if isinstance(v, float) else v) for k_, v in row.items()})
        ex = next(e for e in ex_budget if int(e["c_ratio"]) == cs and float(e["rho"]) == r)
        assert int(ex["opt_m_bb"]) == row["opt_m_exact"] and int(ex["opt_m_kish"]) == row["opt_m_kish"], ex
write_csv("sim_robust_budget.csv", budget_rows)
