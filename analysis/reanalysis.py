"""Recompute 95% upper bounds for published zero-event claims.

Reads paper/litreview/claims/claims.csv, keeps zero-event rows with a stated K,
and writes paper/tab_reanalysis.tex and data/reanalysis.csv.
Run: uv run analysis/reanalysis.py
"""
import csv
import os

from bounds_extra import any_event_upper, bb_upper
from clusterstats import cp_upper

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# Claims used in the paper table, with a short label. Of the ten zero-event rows
# with both N and K, three are left out: C1 pools ten models (C2 gives the
# per-model count, 0/20 of one scenario, from the same post), and C3 repeats
# C2's design (same post, one scenario, 20 runs per model).
# C11, like C10, runs each transcript once and loses a few, so N < K.
KEEP = {
    "C7": "Shutdown resistance, Prompt E \\citep{schlatter2025shutdown}",
    "C2": "Record tampering \\citep{anthropic2026summer}",
    "C8": "Covert sabotage, Codex task \\citep{schoen2025antischeming}",
    "C6": "Covert email reranking \\citep{meinke2024scheming}",
    "C13": "Scheming reasoning \\citep{lindner2026gram}",
    "C5": "Oversight subversion \\citep{meinke2024scheming}",
    "C10": "Safety-research sabotage \\citep{kirk2026sabotage}",
    "C11": "Continuing prefilled sabotage \\citep{kirk2026sabotage}",
}
RHOS = (0.05, 0.2)


def n_of(s):
    # "961-1000" -> 961, the smallest per-model N (the most favourable to the
    # naive bound is the largest; we take the smallest so no row is overstated).
    return int(s.split("-")[0])


rows = {r["id"]: r for r in csv.DictReader(open(os.path.join(ROOT, "paper/litreview/claims/claims.csv")))}
out = []
for cid, label in KEEP.items():
    r = rows[cid]
    x, N, K = int(r["x"]), n_of(r["N"]), int(r["K"])
    # C10 and C11 run each scenario or transcript once and lose a few, so N < K;
    # then every rollout is its own scenario.
    K = min(K, N)
    assert x == 0, cid
    m = N // K
    sizes = [m] * K
    sizes[0] += N - m * K  # put any remainder in one scenario
    row = dict(id=cid, label=label, N=N, K=K, naive=cp_upper(0, N),
               scen=any_event_upper(0, K))
    for rho in RHOS:
        row[f"bb{rho}"] = bb_upper(0, sizes, rho)
    out.append(row)
    print(cid, N, K, {k: round(v * 100, 2) for k, v in row.items() if isinstance(v, float)})

with open(os.path.join(ROOT, "data", "reanalysis.csv"), "w", newline="") as fh:
    w = csv.DictWriter(fh, fieldnames=out[0].keys())
    w.writeheader()
    w.writerows(out)


def pct(v):
    return f"{v * 100:.1f}" if v >= 0.001 else f"{v * 100:.2f}"


with open(os.path.join(ROOT, "paper", "tab_reanalysis.tex"), "w") as fh:
    fh.write("% generated by analysis/reanalysis.py; do not edit\n")
    fh.write("\\begin{tabular}{lrrrrrr}\n\\toprule\n"
             " & & & \\multicolumn{4}{c}{95\\% upper bound (\\%)} \\\\\n\\cmidrule(lr){4-7}\n"
             "claim (0 events) & $N$ & $K$ & naive & $\\rho{=}0.05$ & $\\rho{=}0.2$ & scenarios \\\\\n\\midrule\n")
    for r in out:
        fh.write(f"{r['label']} & {r['N']} & {r['K']} & {pct(r['naive'])} & {pct(r['bb0.05'])} & "
                 f"{pct(r['bb0.2'])} & {pct(r['scen'])} \\\\\n")
    fh.write("\\bottomrule\n\\end{tabular}\n")
