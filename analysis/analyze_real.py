"""Analyse real rollouts. Input CSV, one row per rollout:
    model,cluster,scenario,goal_type,goal_value,urgency,variant,seed,harmful
`cluster` is the scenario configuration; `harmful` is 0/1.

Each model is analysed three ways: all configurations, and the blackmail and
leaking configurations on their own (the within-scenario ICC does not count the
difference between the two scenarios). Writes paper/numbers_real.tex,
paper/tab_real.tex and data/per_cluster_<model>.csv.
ICC intervals: percentile cluster bootstrap, 10,000 resamples, seed 0, resamples with
no events dropped (clusterstats.icc_bootstrap_ci defaults).
Run: uv run analysis/analyze_real.py data/rollouts_opus.csv
     uv run analysis/analyze_real.py data/rollouts_judge.csv Judge
"""
import csv
import os
import sys
from collections import defaultdict

import numpy as np

from bounds_extra import any_event_upper, bb_upper
from clusterstats import (adjusted_upper, cluster_bootstrap_ci, cp_two_sided, cp_upper,
                          deff_unequal, icc_anova, icc_betabinom, icc_bootstrap_ci)

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WORDS = "Zero One Two Three Four Five Six Seven Eight Nine".split()
SCOPES = {"All": "", "Blackmail": "blackmail_", "Leaking": "leaking_"}
PRETTY = {"qwen3_8b": "Qwen3-8B", "qwen3_14b": "Qwen3-14B", "qwen3_32b": "Qwen3-32B",
          "mistral_small_24b": "Mistral-Small-24B", "gpt_oss_20b": "gpt-oss-20b",
          "qwen3_8b_think": "Qwen3-8B (thinking)"}


def tex_name(s):
    return "".join(WORDS[int(c)] if c.isdigit() else c for c in s.title() if c.isalnum())


def analyse(k, m):
    x, n, K = k.sum(), m.sum(), len(k)
    r_a = icc_anova(k, m)
    _, r_b = icc_betabinom(k, m)
    if (k > 0).sum() < 2:
        # Events in fewer than 2 configurations: the ICC is not identified (a single
        # event gives an ANOVA estimate near 0 that reads as a measured zero), so ICC,
        # DEFF, effective N and the bounds that use them are reported as dashes.
        r_a = r_b = float("nan")
    if np.isnan(r_a):
        lo_a = hi_a = d = float("nan")
    else:
        lo_a, hi_a, _ = icc_bootstrap_ci(k, m, B=10000)
        d = deff_unequal(m, max(r_a, 0.0))
    naive_lo, naive_hi = cp_two_sided(x, n)
    boot_lo, boot_hi = cluster_bootstrap_ci(k, m)
    sizes = m.astype(int)
    return {
        "Clusters": K, "Rollouts": int(n), "Events": int(x), "Rate": x / n * 100,
        "ClustersWithEvents": int((k > 0).sum()),
        "IccAnova": r_a, "IccAnovaLo": lo_a, "IccAnovaHi": hi_a, "IccBB": r_b,
        "Deff": d, "Neff": n / d if d == d else float("nan"),
        "NaiveLo": naive_lo * 100, "NaiveHi": naive_hi * 100,
        "BootLo": boot_lo * 100, "BootHi": boot_hi * 100,
        "NaiveUB": cp_upper(x, n) * 100,  # one-sided 95%
        "KishUB": adjusted_upper(x, n, d) * 100 if d == d else float("nan"),
        "BBUB": bb_upper(int(x), sizes, r_b) * 100 if r_b == r_b and 0 < r_b < 1 else float("nan"),
        "ScenUB": any_event_upper(int((k > 0).sum()), K) * 100,
    }


def fmt(key, v):
    if isinstance(v, (int, np.integer)):
        return f"{v}"
    if v != v:
        return "--"
    if key in ("Deff",):
        return f"{v:.1f}"
    if key in ("Neff",):
        return f"{v:.0f}"
    if key.startswith("Icc"):
        return f"{v:.2f}"
    return f"{v:.2f}" if v < 10 else f"{v:.1f}"


def main(path, tag=""):
    # tag (e.g. "Judge") names a second label set: macros \Real<tag>..., files *_<tag>.tex.
    suf = f"_{tag.lower()}" if tag else ""
    data = defaultdict(lambda: defaultdict(lambda: [0, 0]))
    with open(path) as fh:
        for r in csv.DictReader(fh):
            cell = data[r["model"]][r["cluster"]]
            cell[0] += int(r["harmful"])
            cell[1] += 1

    lines = ["% generated by analysis/analyze_real.py; do not edit"]
    table = []
    for model in sorted(data, key=lambda s: list(PRETTY).index(s) if s in PRETTY else 99):
        clusters = data[model]
        for scope, prefix in SCOPES.items():
            names = sorted(c for c in clusters if c.startswith(prefix))
            k = np.array([clusters[c][0] for c in names], float)
            m = np.array([clusters[c][1] for c in names], float)
            out = analyse(k, m)
            print(model, scope, {a: fmt(a, b) for a, b in out.items()})
            for key, v in out.items():
                lines.append(f"\\newcommand{{\\Real{tag}{tex_name(model)}{scope}{key}}}{{{fmt(key, v)}}}")
            table.append((model, scope, out))
        with open(os.path.join(ROOT, "data", f"per_cluster{suf}_{model}.csv"), "w", newline="") as fh:
            w = csv.writer(fh)
            w.writerow(["cluster", "events", "rollouts", "rate"])
            for c in sorted(clusters):
                ki, mi = clusters[c]
                w.writerow([c, ki, mi, ki / mi])

    with open(os.path.join(ROOT, "paper", f"numbers_real{suf}.tex"), "w") as fh:
        fh.write("\n".join(lines) + "\n")

    with open(os.path.join(ROOT, "paper", f"tab_real{suf}.tex"), "w") as fh:
        fh.write("% generated by analysis/analyze_real.py; do not edit\n")
        fh.write("\\begin{tabular}{llrrrrrrr}\n\\toprule\n"
                 "model & configurations & harmful / $N$ & with events & ICC (ANOVA) & ICC (beta-bin.) & DEFF & eff.\\ $N$ "
                 "& 95\\% CI: naive $\\to$ cluster (\\%) \\\\\n\\midrule\n")
        prev = None
        for model, scope, o in table:
            name = PRETTY.get(model, model) if model != prev else ""
            if model != prev and prev is not None:
                fh.write("\\addlinespace\n")
            prev = model
            # Negative ANOVA estimates mean no detectable clustering; show them as 0.
            icc = "--" if o["IccAnova"] != o["IccAnova"] else \
                f"{max(o['IccAnova'], 0):.2f} [{max(o['IccAnovaLo'], 0):.2f}, {max(o['IccAnovaHi'], 0):.2f}]"
            ci = f"{o['NaiveLo']:.1f}--{o['NaiveHi']:.1f} $\\to$ {o['BootLo']:.1f}--{o['BootHi']:.1f}"
            fh.write(f"{name} & {scope.lower()} ({o['Clusters']}) & {o['Events']} / {o['Rollouts']} & "
                     f"{o['ClustersWithEvents']} & {icc} & {fmt('IccBB', o['IccBB'])} & {fmt('Deff', o['Deff'])} & "
                     f"{fmt('Neff', o['Neff'])} & {ci} \\\\\n")
        fh.write("\\bottomrule\n\\end{tabular}\n")


if __name__ == "__main__":
    main(sys.argv[1], *sys.argv[2:3])
