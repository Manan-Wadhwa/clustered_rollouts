# logit p_ijk = b0 + su * u_i + sv * v_ij, u, v ~ N(0, 1); rollouts are Bernoulli(p_ij).
# Var(total) is computed by Gauss-Hermite quadrature, so N_eff is exact up to
# quadrature error; a Monte Carlo run checks one design.
z, w = hermegauss(80)
w = w / w.sum()
TARGET_RATE = 0.01


def marginal_rate(b0, su, sv):
    return w @ special.expit(b0 + su * z[:, None] + sv * z[None, :]) @ w


# Both settings have the same total logit variance (1.5^2 + 0.5^2), so one
# intercept gives a marginal rate of 1% in both.
B0 = optimize.brentq(lambda b: marginal_rate(b, 1.5, 0.5) - TARGET_RATE, -15, 0)
assert abs(marginal_rate(B0, 0.5, 1.5) - TARGET_RATE) < 1e-12


def nested_neff(su, sv, Kn, W, R):
    p = special.expit(B0 + su * z[:, None] + sv * z[None, :])  # [u, v]
    Ep = w @ p @ w
    Epq = w @ (p * (1 - p)) @ w
    g = p @ w                         # E[p | u]
    h = (p ** 2) @ w - g ** 2         # Var(p | u)
    var_g = w @ (g - Ep) ** 2
    var_S = W * R * Epq + W * R ** 2 * (w @ h) + W ** 2 * R ** 2 * var_g
    n = Kn * W * R
    var_rate = Kn * var_S / n ** 2
    return Ep * (1 - Ep) / var_rate, Ep


SETTINGS = {"scenario-dominant": (1.5, 0.5), "wording-dominant": (0.5, 1.5)}
STRAT = {"add scenarios (1 wording each)": [(k_, 1) for k_ in (10, 30, 100, 300, 1000, 3000)],
         "add wordings (10 scenarios)": [(10, w_) for w_ in (1, 3, 10, 30, 100, 300)]}
nest_rows = []
for sname, (su, sv) in SETTINGS.items():
    for tname, plan in STRAT.items():
        for Kn, W in plan:
            R = N // (Kn * W)
            assert Kn * W * R == N
            neff, Ep = nested_neff(su, sv, Kn, W, R)
            nest_rows.append(dict(setting=sname, sigma_scenario=su, sigma_wording=sv,
                                  strategy=tname, K=Kn, W=W, R=R, prompts=Kn * W,
                                  mean_rate=float(Ep), n_eff=float(neff), deff=float(N / neff)))
for row in nest_rows:
    print({k_: (round(v, 4) if isinstance(v, float) else v) for k_, v in row.items()})
write_csv("sim_extra_nested.csv", nest_rows)

# Monte Carlo check for K=10, W=10, R=30, scenario-dominant
su, sv = SETTINGS["scenario-dominant"]
Kn, W, R = 10, 10, 30
reps = 40000
u = rng.standard_normal((reps, Kn, 1))
v = rng.standard_normal((reps, Kn, W))
Xn = rng.binomial(R, special.expit(B0 + su * u + sv * v)).sum((1, 2)) / N
neff_mc = Xn.mean() * (1 - Xn.mean()) / Xn.var()
neff_ex, Ep = nested_neff(su, sv, Kn, W, R)
print(f"MC check K=10 W=10 R=30: mean rate MC {Xn.mean():.5f} vs {Ep:.5f}; "
      f"N_eff MC {neff_mc:.1f} vs quadrature {neff_ex:.1f}")
assert abs(neff_mc / neff_ex - 1) < 0.05
assert abs(Xn.mean() / Ep - 1) < 0.02

