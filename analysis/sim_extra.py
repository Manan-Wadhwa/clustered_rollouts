def cover_bb(pmf_true, mu, rho_assumed, sizes=SIZES):
    """P(mu <= UB_bb(X)) = P(F_assumed(X; mu) >= alpha), F decreasing in mu."""
    F = np.cumsum(sum_pmf(sizes, mu, rho_assumed))
    return float(pmf_true[F >= ALPHA].sum()), F


def cover_any(mu, rho, K=K, m=M):
    q = -np.expm1(log_p_zero_cluster(mu, m, rho))
    ys = np.arange(K + 1)
    ub = np.array([any_event_upper(y, K) for y in ys])
    return float(stats.binom.pmf(ys, K, q)[ub >= mu].sum()), q


def two_point_pmf(mu, rho, m=M, K=K):
    """X when p_i = c with prob pi, else 0; same mean mu and ICC rho as the Beta."""
    c = mu + rho * (1 - mu)
    pi = mu / c
    one = pi * stats.binom.pmf(np.arange(m + 1), m, c)
    one[0] += 1 - pi
    return _conv_power(one, K, K * m)


