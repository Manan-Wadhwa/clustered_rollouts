# ---- 3. Budget allocation with a scenario-writing cost --------------------------
print("\n== 3. budget allocation ==")
RATIOS = (0, 10, 100)
BRHOS = (0.05, 0.2)
budget_rows, curves = [], {}
for cs in RATIOS:
    B = K * (cs + M)  # buys the reference design, 30 scenarios x 100 rollouts
    mmax = B - cs
    for r in BRHOS:
        grid = np.unique(np.round(np.logspace(0, np.log10(mmax), 250)).astype(int))

        def evaluate(ms):
            out = []
            for m_ in ms:
                K_ = int(B // (cs + m_))
                if K_ >= 1:
                    out.append((int(m_), K_, bb_zero_upper(K_, int(m_), r),
                                adjusted_upper(0, K_ * m_, deff(m_, r))))
            return out

        res = evaluate(grid)
        # refine: every integer m near the coarse optima of both criteria
        mb = min(res, key=lambda t: t[2])[0]
        mk = min(res, key=lambda t: t[3])[0]
        near = set()
        for c0 in (mb, mk):
            near |= set(range(max(1, int(c0 / 1.6)), min(mmax, int(c0 * 1.6) + 2) + 1))
        res = sorted(set(res) | set(evaluate(sorted(near))))
        curves[(cs, r)] = res
        bm, bK, bub, _ = min(res, key=lambda t: t[2])
        km, kK, _, kub = min(res, key=lambda t: t[3])
        classical = np.sqrt(cs * (1 - r) / r)
        # bb bound at the integer m closest to the classical optimum (at least 1)
        mc_int = max(1, int(round(classical)))
        cK = int(B // (cs + mc_int))
        cub = bb_zero_upper(cK, mc_int, r)
        ref = bb_zero_upper(K, M, r)
        row = dict(c_ratio=cs, rho=r, budget=B, opt_m_bb=bm, opt_K_bb=bK, opt_ub_bb=bub,
                   opt_m_kish=km, opt_K_kish=kK, classical_m=classical,
                   ub_bb_at_classical=cub, K_at_classical=cK, ub_bb_reference_30x100=ref)
        budget_rows.append(row)
        print({k_: (round(v, 5) if isinstance(v, float) else v) for k_, v in row.items()})
