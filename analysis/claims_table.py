"""Appendix table of every collected zero-event claim, with its verbatim quote.

Reads paper/litreview/claims/claims.csv and data/reanalysis.csv.
Writes paper/tab_claims.tex (a longtable).
Run: python3 analysis/claims_table.py   (standard library only)
"""
import csv
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

CITE = {
    "https://alignment.anthropic.com/2026/agentic-misalignment-summer-2026/": "anthropic2026summer",
    "https://arxiv.org/pdf/2510.05179": "lynch2025agentic",
    "https://arxiv.org/pdf/2412.04984": "meinke2024scheming",
    "https://arxiv.org/pdf/2509.14260": "schlatter2025shutdown",
    "https://arxiv.org/pdf/2509.15541": "schoen2025antischeming",
    "https://arxiv.org/pdf/2604.24618": "kirk2026sabotage",
    "https://metr.org/evaluations/gpt-5-report/": "metr2025gpt5",
    "https://arxiv.org/pdf/2605.30322": "lindner2026gram",
}

# Why a row is not in Table 3 (kept in step with analysis/reanalysis.py).
WHY = {
    "C1": "pools ten models; C2 gives the per-model count",
    "C3": "same design as C2 (one scenario, 20 runs)",
    "C4": "one event, not zero",
    "C9": "$K$ not stated",
    "C12": "$K$ not stated",
}

ESC = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
       "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
       "\u2264": r"$\le$", "\u00d7": r"$\times$", "\u2014": "--", "\u2013": "--",
       "\u201c": "``", "\u201d": "''", "\u2018": "`", "\u2019": "'", "\u2265": r"$\ge$"}


def tex(s):
    return "".join(ESC.get(ch, ch) for ch in s)


claims = list(csv.DictReader(open(os.path.join(ROOT, "paper", "litreview", "claims", "claims.csv"))))
kept = {r["id"] for r in csv.DictReader(open(os.path.join(ROOT, "data", "reanalysis.csv")))}
for c in claims:
    assert c["url"] in CITE, c["url"]
    assert (c["id"] in kept) != (c["id"] in WHY), c["id"]

HEAD = "id & source, behaviour & quote & $N$ & $K$ & in Table~\\ref{tab:reanalysis}? \\\\\n"
with open(os.path.join(ROOT, "paper", "tab_claims.tex"), "w") as fh:
    fh.write("% generated by analysis/claims_table.py; do not edit\n")
    fh.write("\\begin{longtable}{@{}>{\\raggedright\\arraybackslash}p{0.04\\linewidth}>{\\raggedright\\arraybackslash}p{0.17\\linewidth}"
             ">{\\raggedright\\arraybackslash}p{0.40\\linewidth}rr>{\\raggedright\\arraybackslash}p{0.13\\linewidth}@{}}\n"
             "\\caption{All collected claims. $N$ is rollouts and $K$ distinct scenarios or prompts, "
             "as stated or derived from the source's design.}\\label{tab:claims}\\\\\n\\toprule\n"
             + HEAD + "\\midrule\n\\endfirsthead\n\\toprule\n" + HEAD + "\\midrule\n\\endhead\n")
    for c in claims:
        used = "yes" if c["id"] in kept else "no: " + WHY[c["id"]]
        fh.write(f"{c['id']} & \\citet{{{CITE[c['url']]}}}, {tex(c['behaviour'])} & "
                 f"``{tex(c['quote'])}'' & {tex(c['N'])} & {tex(c['K']) or '--'} & {used} \\\\\n")
    fh.write("\\bottomrule\n\\end{longtable}\n")
print(f"{len(claims)} claims, {len(kept)} kept")
